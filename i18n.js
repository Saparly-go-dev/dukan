// Kategoriýalar maglumatlarda türkmençe saklanýar, görkezilende terjime edilýär
const CATEGORIES = { 'Azyk önümleri': 'cat.food', 'Içgiler': 'cat.drinks', 'Arassaçylyk': 'cat.hygiene', 'Kanselýariýa': 'cat.stationery' };

const LANG_KEY = 'dukan-lang';
let lang = (() => {
  try { const l = localStorage.getItem(LANG_KEY); if (I18N[l]) return l; } catch {}
  return 'tk';
})();

function t(key, vars = {}) {
  const s = I18N[lang][key] ?? I18N.tk[key] ?? key;
  return typeof s === 'string' ? s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '') : s;
}

// Sana görä söz görnüşi: "5 продаж", "1 sale", "3 haryt"
function plural(n, key) {
  const f = t(key);
  if (f.length === 1) return f[0];
  if (lang === 'ru') {
    const m10 = n % 10, m100 = n % 100;
    return f[m10 === 1 && m100 !== 11 ? 0 : m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14) ? 1 : 2];
  }
  return f[n === 1 ? 0 : 1];
}

const catName = c => CATEGORIES[c] ? t(CATEGORIES[c]) : c;

// Elementiň diňe öz tekstini çalyşýar, içindäki nyşanlara (ikonalara, inputlara) degmeýär
function setOwnText(el, text) {
  const node = [...el.childNodes].find(n => n.nodeType === 3 && n.data.trim());
  if (!node) { el.textContent = text; return; }
  const [, lead, , trail] = node.data.match(/^(\s*)([\s\S]*?)(\s*)$/);
  node.data = lead + text + trail;
}

function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach(el => setOwnText(el, t(el.dataset.i18n)));
  document.querySelectorAll('[data-i18n-ph]').forEach(el => el.placeholder = t(el.dataset.i18nPh));
  document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  document.querySelectorAll('[data-lang]').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
}
